import { test, expect } from "@playwright/test";
import { readFile } from "node:fs/promises";

test("local AWS account: real Auth and shared S3 connection roundtrip", async ({ page }, info) => {
  test.skip(!process.env.FIRECRAB_STORAGE_QA_ACCOUNT_CREDENTIALS, "Requires explicit local-account QA");
  const credentials = JSON.parse(process.env.FIRECRAB_STORAGE_QA_ACCOUNT_CREDENTIALS!);
  await page.addInitScript(() => localStorage.setItem("firecrab.locale", "en"));
  await page.goto("/#/pipe/auth");
  await page.getByRole("button", { name: "Connect AWS", exact: true }).click();
  await page.getByLabel("AWS access key ID", { exact: true }).fill(credentials.AccessKeyId);
  await page.getByLabel("AWS secret access key", { exact: true }).fill(credentials.SecretAccessKey);
  if (credentials.SessionToken) await page.getByLabel("AWS session token (optional)", { exact: true }).fill(credentials.SessionToken);
  await page.getByLabel("AWS region", { exact: true }).fill(process.env.FIRECRAB_STORAGE_QA_REGION!);
  await page.getByRole("button", { name: "Verify and connect", exact: true }).click();
  await expect(page.getByRole("cell", { name: new RegExp(process.env.FIRECRAB_STORAGE_QA_ACCOUNT!) })).toBeVisible();
  await expect(page.locator('input[type="password"]')).toHaveCount(0);
  await page.screenshot({ path: info.outputPath("aws-account-connected.png"), fullPage: true });
  await page.goto("/#/pipe/storage");
  const panel = page.getByRole("region", { name: "PipeStorage", exact: true });
  await page.getByRole("button", { name: "Add S3 connection", exact: true }).click();
  await page.getByLabel("Name", { exact: true }).fill("Local AWS account QA");
  await page.getByLabel("Bucket", { exact: true }).fill(process.env.FIRECRAB_STORAGE_QA_BUCKET!);
  await page.getByLabel("Region", { exact: true }).fill(process.env.FIRECRAB_STORAGE_QA_REGION!);
  await page.getByLabel("Prefix (optional)", { exact: true }).fill("qa/");
  await page.getByRole("button", { name: "Verify and save", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("Connection verified and saved");
  await page.getByRole("row").filter({ has: page.getByRole("cell", { name: "Local AWS account QA", exact: true }) }).getByRole("button", { name: "Browse", exact: true }).click();
  const data = Buffer.from("Actual local AWS account / Auth / PipeStorage / S3 roundtrip\n");
  await page.getByLabel("File", { exact: true }).setInputFiles({ name: "account-console-proof.txt", mimeType: "text/plain", buffer: data });
  await page.getByRole("button", { name: "Upload", exact: true }).click();
  await expect(panel.getByRole("status")).toContainText("Upload complete");
  const row = page.getByRole("row").filter({ has: page.getByRole("cell", { name: "qa/account-console-proof.txt", exact: true }) });
  const pending = page.waitForEvent("download");
  await row.getByRole("button", { name: "Download", exact: true }).click();
  const downloaded = await (await pending).path();
  expect(await readFile(downloaded!)).toEqual(data);
  await page.getByRole("region", { name: "S3 object browser", exact: true }).screenshot({ path: info.outputPath("pipe-storage-account-roundtrip.png") });
  await panel.getByRole("heading", { name: "PipeStorage · Amazon S3", exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: info.outputPath("pipe-storage-account-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("pipe-storage-account-mobile.png"), fullPage: true });
  page.once("dialog", dialog => dialog.accept());
  await row.getByRole("button", { name: "Delete object", exact: true }).click();
  await expect(row).toHaveCount(0);
});
